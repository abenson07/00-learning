/**
 * Reads lessons-01-07.json and writes supabase/seed_lesson_plans.sql
 * (DDL + RLS + idempotent INSERT). Run: node scripts/generate-lesson-plan-seed.mjs
 */
import fs from "fs";
import path from "path";
import { fileURLToPath } from "url";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const root = path.join(__dirname, "..");
const jsonPath = path.join(root, "lessons-01-07.json");
const outPath = path.join(root, "supabase", "seed_lesson_plans.sql");

const raw = JSON.parse(fs.readFileSync(jsonPath, "utf8"));
const lp = raw.lesson_plan;
if (!lp || typeof lp.id !== "string") {
  throw new Error("lessons-01-07.json: missing lesson_plan.id");
}

const slug = lp.id;
const title = lp.title ?? "";
const description = lp.description ?? "";

/** Inner JSON stored in content column (matches TypeScript LessonPlanContent). */
const contentObj = {
  id: lp.id,
  title: lp.title,
  description: lp.description,
  lessons: lp.lessons ?? [],
};

const contentJson = JSON.stringify(contentObj);

function pgQuoteLiteral(str) {
  return "'" + String(str).replace(/'/g, "''") + "'";
}

const sql = `-- Generated by scripts/generate-lesson-plan-seed.mjs — do not edit by hand.
-- Re-run: node scripts/generate-lesson-plan-seed.mjs

CREATE TABLE IF NOT EXISTS public.lesson_plans (
  slug text PRIMARY KEY,
  title text NOT NULL,
  description text NOT NULL,
  content jsonb NOT NULL,
  updated_at timestamptz NOT NULL DEFAULT now()
);

ALTER TABLE public.lesson_plans ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS "lesson_plans_select_public" ON public.lesson_plans;
CREATE POLICY "lesson_plans_select_public"
  ON public.lesson_plans
  FOR SELECT
  TO anon, authenticated
  USING (true);

GRANT SELECT ON public.lesson_plans TO anon, authenticated;

INSERT INTO public.lesson_plans (slug, title, description, content)
VALUES (
  ${pgQuoteLiteral(slug)},
  ${pgQuoteLiteral(title)},
  ${pgQuoteLiteral(description)},
  ${pgQuoteLiteral(contentJson)}::jsonb
)
ON CONFLICT (slug) DO UPDATE SET
  title = EXCLUDED.title,
  description = EXCLUDED.description,
  content = EXCLUDED.content,
  updated_at = now();
`;

fs.mkdirSync(path.dirname(outPath), { recursive: true });
fs.writeFileSync(outPath, sql, "utf8");
console.log(`Wrote ${outPath} (${(sql.length / 1024).toFixed(1)} KB)`);
